#ifndef ADAPTIVE_JSON5_DETAIL_POWER_OF_FIVE_TABLE_HPP_
#define ADAPTIVE_JSON5_DETAIL_POWER_OF_FIVE_TABLE_HPP_

#include <cstddef>
#include <cstdint>

namespace adaptive_json5::detail
{
  /**
   * @brief 128-bit approximation of one power of five for the Eisel-Lemire conversion step.
   * @par Requirements
   * J5-037; J5-039.
   * @note high holds bits 127..64 and always has bit 63 set; low holds bits 63..0.
   */
  struct power_of_five_128
  {
      std::uint64_t high;
      std::uint64_t low;
  };

  constexpr std::int32_t c_smallest_power_of_five = -342;
  constexpr std::int32_t c_largest_power_of_five = 308;
  constexpr std::size_t c_power_of_five_count =
    static_cast<std::size_t>(c_largest_power_of_five - c_smallest_power_of_five) + 1U;

  /**
   * @brief Normalized 128-bit approximations of 5^q for q = -342..308, at index q + 342.
   * @par Requirements
   * J5-037; J5-039.
   * @note Generated by tools/generate_power_of_five_table.py from the definition in
   * Lemire (2021), "Number Parsing at a Gigabyte per Second"; see that script for the rules.
   * q >= 0 entries are truncated; q < 0 entries are reciprocals rounded up.
   * Built only when ADAPTIVE_JSON5_EISEL_LEMIRE is ON (ADR 0005, decision 3).
   */
  extern const power_of_five_128 c_power_of_five_table[c_power_of_five_count];
} // namespace adaptive_json5::detail

#endif /* ADAPTIVE_JSON5_DETAIL_POWER_OF_FIVE_TABLE_HPP_ */
