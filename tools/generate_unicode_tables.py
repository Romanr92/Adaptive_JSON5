#!/usr/bin/env python3
"""Generate the authorized Unicode property header from pinned, offline UCD inputs."""

# SPDX-License-Identifier: Apache-2.0
import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "tools/unicode-data"
START_CATEGORIES = {"Lu", "Ll", "Lt", "Lm", "Lo", "Nl"}
EXTRA_CATEGORIES = {"Mn", "Mc", "Nd", "Pc"}


def read_categories(path):
    """Expand UCD First/Last records as intervals, without locale classification."""
    categories = {}
    pending = None
    previous = -1
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line:
            continue
        fields = line.split(";")
        if len(fields) != 15:
            raise ValueError(f"{path}:{line_number}: expected 15 UCD fields")
        value = int(fields[0], 16)
        name, category = fields[1:3]
        if not previous < value <= 0x10FFFF:
            raise ValueError(f"{path}:{line_number}: unordered or invalid code point")
        previous = value
        if name.endswith(", First>"):
            if pending is not None:
                raise ValueError("Nested UCD range")
            pending = (value, name[:-len(", First>")], category)
            continue
        if name.endswith(", Last>"):
            if pending is None or pending[1:] != (name[:-len(", Last>")], category):
                raise ValueError("Unmatched UCD range endpoint")
            first = pending[0]
            pending = None
        else:
            if pending is not None:
                raise ValueError("UCD range has no matching Last record")
            first = value
        categories.setdefault(category, []).append((first, value))
    if pending is not None:
        raise ValueError("Unterminated UCD range")
    return categories


def merge_ranges(categories, *databases):
    """Union memberships and merge overlapping or adjacent inclusive intervals."""
    intervals = sorted(
        interval
        for database in databases
        for category in categories
        for interval in database.get(category, [])
    )
    merged = []
    for first, last in intervals:
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "include/adaptive_json5/unicode_tables.hpp")
    arguments = parser.parse_args()
    manifest = json.loads((DATA / "sources.json").read_text(encoding="utf-8"))
    for name, source in manifest.items():
        actual = hashlib.sha256((DATA / name).read_bytes()).hexdigest()
        if actual != source["sha256"]:
            raise ValueError("Pinned source hash mismatch: " + name)

    modern = read_categories(DATA / "17.0.0/UnicodeData.txt")
    baseline = read_categories(DATA / "3.0.0/UnicodeData.txt")
    tables = {
        "c_identifier_start_ranges": merge_ranges(START_CATEGORIES, modern, baseline),
        "c_identifier_extra_ranges": merge_ranges(EXTRA_CATEGORIES, modern, baseline),
        "c_space_separator_ranges": merge_ranges({"Zs"}, modern),
        "c_unicode_3_space_separator_ranges": merge_ranges({"Zs"}, baseline),
    }

    # Embed the complete upstream notice so the standalone header retains attribution.
    license_text = (ROOT / "LICENSES/Unicode-License-V3.txt").read_text(encoding="utf-8")
    lines = ["// Generated by tools/generate_unicode_tables.py; do not edit table entries.",
             "// Unicode data copyright 1991-2026 Unicode, Inc.; UCD 17.0.0 ReadMe copyright 2025 Unicode, Inc.",
             "// SPDX-License-Identifier: Unicode-3.0", "/*", *license_text.splitlines(), "*/", "",
             "#ifndef UNICODE_TABLES_HPP_", "#define UNICODE_TABLES_HPP_", "",
             '#include "unicode_range.hpp"', "", "namespace adaptive_json5", "{", "  namespace detail", "  {"]
    for version in ("17.0.0", "3.0.0"):
        source = manifest[version + "/UnicodeData.txt"]
        lines += ["    // " + source["url"], "    // SHA-256: " + source["sha256"]]
    lines += ["", "    // Identifiers preserve Unicode 3.0 category memberships and add Unicode 17.0.0 memberships.",
              "    // Space separators use Unicode 17.0.0 Zs. A separate legacy table supports later whitespace policy.",
              "    inline constexpr char c_unicode_data_version[] = \"17.0.0\";",
              "    inline constexpr char c_unicode_identifier_baseline_version[] = \"3.0.0\";", "",
              "    // Keep one interval per line for reproducible generation and review.", "    // clang-format off"]
    for name, ranges in tables.items():
        count = sum(last - first + 1 for first, last in ranges)
        lines += ["", "    /**", "     * @brief Immutable inclusive property ranges: " + name + ".",
                  "     * @par Requirements", "     * P006; J5-006.",
                  f"     * @note Sorted, disjoint intervals; {len(ranges)} ranges containing {count} code points.",
                  "     */", f"    inline constexpr unicode_range {name}[] =", "    {"]
        lines.extend(f"      {{0x{first:06X}, 0x{last:06X}}}," for first, last in ranges)
        lines.append("    };")
        print(f"{name}: {len(ranges)} ranges, {count} code points")
    lines += ["", "    // clang-format on", "  } // namespace detail", "} // namespace adaptive_json5", "",
              "#endif /* UNICODE_TABLES_HPP_ */", ""]
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    with arguments.output.open("w", encoding="utf-8", newline="\n") as output:
        output.write("\n".join(lines))


if __name__ == "__main__":
    main()
