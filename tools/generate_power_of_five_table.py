#!/usr/bin/env python3
"""Generate the 128-bit power-of-five table used by the Eisel-Lemire conversion step."""

# SPDX-License-Identifier: Apache-2.0
#
# Each entry approximates 5^q, q = -342..308, as a 128-bit integer T with its top bit set
# (2^127 <= T < 2^128), following the definition in Daniel Lemire, "Number Parsing at a
# Gigabyte per Second", Software: Practice and Experience 51(8), 2021. Only the published
# mathematics is used; no third-party code or data is copied.
#
#   q >= 0:       normalize 5^q to 128 bits, truncating dropped low bits.
#   -27 <= q < 0: T = floor(2^(z + 127) / 5^-q) + 1, where z is the smallest integer with
#                 2^z >= 5^-q.
#   q < -27:      C = floor(2^(2z + 128) / 5^-q) + 1, then halve C until it is below 2^128.
#
# The build never runs this script; its output is checked in. Regenerate with:
#   python tools/generate_power_of_five_table.py

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SMALLEST_POWER = -342
LARGEST_POWER = 308
TOP_BIT = 1 << 127
LIMIT = 1 << 128
LOW_MASK = (1 << 64) - 1


def smallest_covering_exponent(value):
    """Return the smallest z with 2^z >= value."""
    z = 0
    while (1 << z) < value:
        z += 1
    return z


def power_of_five_128(q):
    """Return the normalized 128-bit approximation of 5^q."""
    if q >= 0:
        value = 5**q
        while value < TOP_BIT:
            value <<= 1
        while value >= LIMIT:
            value >>= 1
        return value

    divisor = 5**-q
    z = smallest_covering_exponent(divisor)
    if q >= -27:
        return (2 ** (z + 127)) // divisor + 1

    value = (2 ** (2 * z + 128)) // divisor + 1
    while value >= LIMIT:
        value //= 2
    return value


def build_table():
    """Compute every entry and check the normalization invariant and known anchors."""
    table = [(q, power_of_five_128(q)) for q in range(SMALLEST_POWER, LARGEST_POWER + 1)]
    for q, value in table:
        if not TOP_BIT <= value < LIMIT:
            raise ValueError(f"5^{q} is not normalized to 128 bits")
    entries = dict(table)
    # Exact anchors: 5^0 = 1 and 5^1 = 5 are exact; 1/5 = 0.CCCC... rounds up in its last bit.
    if entries[0] != TOP_BIT or entries[1] != 5 << 125 or entries[-1] != int("CC" * 15 + "CD", 16):
        raise ValueError("Anchor entries do not match their exact values")
    return table


def render(table):
    """Render the generated C++ source."""
    lines = [
        "// Generated by tools/generate_power_of_five_table.py; do not edit table entries.",
        "// SPDX-License-Identifier: Apache-2.0",
        '#include "value/power_of_five_table.hpp"',
        "",
        "namespace adaptive_json5::detail",
        "{",
        "  // One entry per line, q = -342..308, for reproducible generation and review.",
        "  // clang-format off",
        "  const power_of_five_128 c_power_of_five_table[c_power_of_five_count] = {",
    ]
    for q, value in table:
        lines.append(f"    {{0x{value >> 64:016X}U, 0x{value & LOW_MASK:016X}U}}, // 5^{q}")
    lines += ["  };", "  // clang-format on", "} // namespace adaptive_json5::detail", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "core/src/value/power_of_five_table.cpp")
    arguments = parser.parse_args()
    arguments.output.write_text(render(build_table()), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
